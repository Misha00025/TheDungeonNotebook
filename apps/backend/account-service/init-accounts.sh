#!/bin/bash
set -euo pipefail

: "${ACCOUNTS_DATABASE:?ACCOUNTS_DATABASE is required}"
: "${ACCOUNTS_MYSQL_USER:?ACCOUNTS_MYSQL_USER is required}"
: "${ACCOUNTS_MYSQL_PASSWORD:?ACCOUNTS_MYSQL_PASSWORD is required}"
: "${MYSQL_ROOT_PASSWORD:?MYSQL_ROOT_PASSWORD is required}"

[[ "$ACCOUNTS_DATABASE" =~ ^[A-Za-z0-9_]+$ ]]
[[ "$ACCOUNTS_MYSQL_USER" =~ ^[A-Za-z0-9_]+$ ]]
escaped_password=${ACCOUNTS_MYSQL_PASSWORD//\'/\'\'}
sql="CREATE DATABASE IF NOT EXISTS \`$ACCOUNTS_DATABASE\`; CREATE USER IF NOT EXISTS '$ACCOUNTS_MYSQL_USER'@'%' IDENTIFIED BY '$escaped_password'; GRANT ALL PRIVILEGES ON \`$ACCOUNTS_DATABASE\`.* TO '$ACCOUNTS_MYSQL_USER'@'%';"
mysql -u root -p"$MYSQL_ROOT_PASSWORD" -e "SET SESSION sql_mode = CONCAT_WS(',', @@sql_mode, 'NO_BACKSLASH_ESCAPES'); $sql"
