// Сессия — зона ответственности хаба.
//
// Хаб решает, что пользователь не залогинен (гейт), и прокидывает сессию
// в remotes. Remotes при автономном запуске (без хаба) грузят сессию из
// хранилища (fallback) — см. session.ts в shared.
//
// Здесь — только типы контракта сессии, которую хаб передаёт в remotes.

export interface HubSession {
  /** Access-токен (может быть null, если пользователь не залогинен). */
  accessToken: string | null;
  /** Идентификатор пользователя (null, если не залогинен). */
  userId: number | null;
  /** API_BASE из config.json хаба — прокидывается в remotes, чтобы они
   *  стучались на тот же шлюз, а не на фолбэк localhost:5000. */
  apiBase: string;
}
